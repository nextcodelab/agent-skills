#!/usr/bin/env python3
"""Generate a complete Markdown tree of this portable toolkit."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / "FILE_TREE.md"

def render(directory: Path, prefix: str = "") -> list[str]:
    entries = [p for p in sorted(directory.iterdir(), key=lambda p: (p.is_file(), p.name.casefold())) if p != DEST and p.name != "__pycache__"]
    rows: list[str] = []
    for i, path in enumerate(entries):
        last = i == len(entries) - 1
        rows.append(prefix + ("└── " if last else "├── ") + path.name + ("/" if path.is_dir() else ""))
        if path.is_dir() and not path.is_symlink():
            rows.extend(render(path, prefix + ("    " if last else "│   ")))
    return rows

def main() -> None:
    text = "# Video Editors Toolkit — Complete File Tree\n\nGenerated by `tools/inventory/build_tree.py`. This includes bundled runtimes, model files, packages, projects, assets, and skills; this generated file and Python `__pycache__` folders are omitted. Regenerate after reorganizing the toolkit.\n\n```text\nvideo-editors/\n" + "\n".join(render(ROOT)) + "\n```\n"
    DEST.write_text(text, encoding="utf-8")
    print(f"Wrote {DEST} ({len(text.splitlines())} lines)")

if __name__ == "__main__": main()
